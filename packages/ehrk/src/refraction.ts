const toDeg = ([deg, min]: readonly [number, number]): number => {
  const sign = deg < 0 || Object.is(deg, -0) ? -1 : 1;
  return sign * (Math.abs(deg) + min / 60);
};

const ROWS = refraction.map((r) => ({
  h: toDeg(r.h),
  refr: r.refr,
}));

export function refractionAt(trueAltDeg: number): number {
  const first = ROWS[0]!;
  const last = ROWS[ROWS.length - 1]!;
  if (trueAltDeg <= first.h) return first.refr / 60;
  if (trueAltDeg >= last.h) return 0;
  for (let i = 1; i < ROWS.length; i++) {
    const lo = ROWS[i - 1]!;
    const hi = ROWS[i]!;
    if (trueAltDeg <= hi.h) {
      const t = (trueAltDeg - lo.h) / (hi.h - lo.h);
      return (lo.refr + t * (hi.refr - lo.refr)) / 60;
    }
  }
  return 0;
}
